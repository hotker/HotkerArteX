// 固定 whitespace-pre + font-mono，并按容器宽度连续缩放字号（CSS clamp），让左栏
// 无论多宽都完整显示，而不是裁掉右边一列。
//
// 宽度自适应：父容器给定 --art-media（媒体区可用宽度，px 或 cqw 均可），
// 字号 = 该宽度 / 列数 × 系数，再被 [MIN_PX, MAX_PX] 夹住；超出时横向可滚动。
