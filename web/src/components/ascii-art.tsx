const COLS = 107;
const ROWS = 45;
const MIN_PX = 4.5;
const MAX_PX = 12;

export function AsciiArt({ className }: { className?: string }) {
  return (
    <div className={className}>
      <pre
        aria-hidden
        className="w-full select-none overflow-x-auto overflow-y-hidden font-mono leading-[1.12] whitespace-pre"
        style={{
          // 1.667 ≈ 1/0.6：等宽字宽约 0.6em，乘以它让 107 列刚好铺满容器宽度。
          fontSize: `clamp(${MIN_PX}px, calc(var(--art-media, 360px) / ${COLS} * 1.667), ${MAX_PX}px)`,
          aspectRatio: `${COLS} / ${ROWS}`,
          fontVariantLigatures: "none",
        }}
      >
        {ART}
      </pre>
    </div>
  );
}
